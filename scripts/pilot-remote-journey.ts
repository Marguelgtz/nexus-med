// Synthetic-only smoke against the explicitly configured isolated pilot.
// Messages stay in its encrypted outbox; this script never sends SMTP mail.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { randomBytes, randomUUID } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { decryptEmailPayload } from '../apps/api/src/domains/email/outbox';
import type { AdministrativePatient, Appointment, AuthSession, EncounterDetail, MedicalDocument, StudyReceipt, StudyRequest } from '@nexus-med/contracts';

const origin = 'https://nexus-med-pilot-001-web.marguel-gtz.workers.dev';
const configPath = 'apps/api/wrangler.pilot.jsonc';
const config = JSON.parse(readFileSync(configPath, 'utf8'));
if (config.name !== 'nexus-med-pilot-001-api' || config.vars.APP_BASE_URL !== origin ||
    config.d1_databases.find((db: {binding: string}) => db.binding === 'DB')?.database_id !== '00346f91-cfac-468e-adee-dc09a0e28328' ||
    config.r2_buckets[0].bucket_name !== 'nexus-med-pilot-001-study-files') throw new Error('Pilot bindings do not match the approved isolated environment.');
const secret = readFileSync('.local/pilot-001/better-auth-secret', 'utf8').trim();
type Identity = { id: string; email: string; cookie: string; clinicId?: string };
type ResumeState = { runId: string; password: string; passwordSetFor: string[] };
const resumeStatePath = '.local/pilot-001/remote-journey-state.json';
const syntheticLabels = ['doctor1','doctor2','secretary1','secretary2','outsider'] as const;
let runId = '';
let password = '';
let resumeState: ResumeState | null = null;

function saveResumeState(state: ResumeState) {
  mkdirSync('.local/pilot-001', { recursive: true, mode: 0o700 });
  const temporaryPath = `${resumeStatePath}.tmp`;
  writeFileSync(temporaryPath, JSON.stringify(state), { mode: 0o600 });
  chmodSync(temporaryPath, 0o600);
  renameSync(temporaryPath, resumeStatePath);
  chmodSync(resumeStatePath, 0o600);
}

function prepareResumeState(databaseRunId: string) {
  if (existsSync(resumeStatePath)) {
    chmodSync(resumeStatePath, 0o600);
    const loaded = JSON.parse(readFileSync(resumeStatePath, 'utf8')) as Partial<ResumeState>;
    assert.equal(loaded.runId, databaseRunId, 'Saved synthetic password belongs to a different pilot run');
    assert.equal(typeof loaded.password, 'string');
    assert.ok((loaded.password?.length ?? 0) >= 32);
    assert.ok(Array.isArray(loaded.passwordSetFor));
    assert.ok(loaded.passwordSetFor.every(label => syntheticLabels.includes(label as typeof syntheticLabels[number])));
    resumeState = loaded as ResumeState;
  } else {
    resumeState = { runId: databaseRunId, password: `Synthetic-${randomBytes(24).toString('hex')}!`, passwordSetFor: [] };
    saveResumeState(resumeState);
  }
  runId = resumeState.runId;
  password = resumeState.password;
}

function markPasswordSet(label: string) {
  assert.ok(resumeState);
  if (!resumeState.passwordSetFor.includes(label)) {
    resumeState.passwordSetFor.push(label);
    saveResumeState(resumeState);
  }
}

function queryPilot(sql: string): Record<string, unknown>[] {
  const result = spawnSync(process.execPath, ['node_modules/wrangler/bin/wrangler.js','d1','execute','DB','--remote','--config',configPath,'--command',sql,'--json'], {
    encoding:'utf8', env:{...process.env,WRANGLER_WRITE_LOGS:'false',WRANGLER_SEND_METRICS:'false'},
  });
  if (result.status !== 0) throw new Error('Unable to read the synthetic pilot database.');
  return JSON.parse(result.stdout)[0]?.results ?? [];
}

async function request(path: string, body?: unknown, cookie = '', method = body === undefined ? 'GET' : 'POST') {
  const headers = new Headers({ Origin: origin });
  if (cookie) headers.set('Cookie', cookie);
  const multipart = body instanceof FormData;
  if (body !== undefined && !multipart) headers.set('Content-Type', 'application/json');
  return fetch(new URL(path, origin), { method, headers, redirect: 'manual', ...(body === undefined ? {} : {body: multipart ? body : JSON.stringify(body)}) });
}
async function json<T = unknown>(response: Response, status = 200): Promise<T> {
  assert.equal(response.status, status, `Unexpected HTTP status (${response.status}), expected ${status}`);
  return response.json() as Promise<T>;
}
function sessionCookie(response: Response): string {
  const values = response.headers.getSetCookie().map(item => item.split(';',1)[0] ?? '').filter(item => item.includes('session_token='));
  assert.equal(values.length, 1, 'Expected one session cookie');
  return values[0]!;
}
async function capturedUrl(email: string, kind: 'verify_email' | 'invitation' | 'reset_password'): Promise<URL> {
  // All addresses are generated by this run; SQL literals contain only UUIDs and fixed text.
  assert.match(email, /^pilot-[a-f0-9-]+-[a-z0-9]+@example\.test$/);
  const sql = `SELECT encryptedBody FROM email_outbox WHERE recipient = '${email}' AND kind = '${kind}' ORDER BY createdAt DESC LIMIT 1`;
  const rows = queryPilot(sql);
  assert.equal(rows.length, 1, 'Expected one synthetic message');
  const encryptedBody = rows[0]?.encryptedBody;
  if (typeof encryptedBody !== 'string') throw new Error('The synthetic message payload is unavailable.');
  const payload = await decryptEmailPayload(secret, encryptedBody);
  const linkText = payload.text.match(/https?:\/\/[^\s]+/)?.[0];
  assert.ok(linkText);
  const link = new URL(linkText);
  assert.equal(link.origin, origin, 'Email link has unexpected origin');
  return link;
}
async function signup(label: string): Promise<Identity> {
  const email = `pilot-${runId}-${label}@example.test`;
  await json(await request('/api/auth/sign-up/email', {name:`Personal sintético ${label}`,email,password}));
  const link = await capturedUrl(email, 'verify_email');
  assert.ok([200,302].includes((await request(`${link.pathname}${link.search}`)).status), 'Verification failed');
  const signIn = await request('/api/auth/sign-in/email', {email,password});
  assert.equal(signIn.status, 200, 'Sign-in failed');
  const cookie = sessionCookie(signIn);
  const session = await json<AuthSession>(await request('/api/session', undefined, cookie));
  assert.equal(session.onboardingRequired, true);
  return {id:session.user.id,email,cookie};
}
async function owner(label: string): Promise<Identity> {
  const identity = await signup(label);
  const session = await json<AuthSession>(await request('/api/onboarding/clinic', {name:`Consultorio sintético ${label}`},identity.cookie));
  assert.equal(session.canManageAccess,true);
  const clinic = session.clinic;
  assert.ok(clinic);
  return {...identity,clinicId:clinic.id};
}
async function recoverIdentity(row: Record<string, unknown>, label: string): Promise<Identity> {
  const email = String(row.email);
  const id = String(row.id);
  assert.match(email, new RegExp(`^pilot-[a-f0-9-]+-${label}@example\\.test$`));
  if (!resumeState?.passwordSetFor.includes(label)) {
    let resetRequest = await request('/api/auth/request-password-reset',{email,redirectTo:`${origin}/restablecer-contrasena`});
    for (let retries=0; resetRequest.status === 429 && retries<3; retries++) {
      const retryAfter = Number(resetRequest.headers.get('X-Retry-After') ?? resetRequest.headers.get('Retry-After'));
      assert.ok(Number.isSafeInteger(retryAfter) && retryAfter > 0 && retryAfter <= 3600,'Rate limit did not provide a safe retry window');
      console.log('Synthetic password-reset limit reached; waiting for its Retry-After window.');
      await new Promise(resolve => setTimeout(resolve,(retryAfter + 2) * 1000));
      resetRequest = await request('/api/auth/request-password-reset',{email,redirectTo:`${origin}/restablecer-contrasena`});
    }
    await json(resetRequest);
    const reset = await capturedUrl(email,'reset_password');
    assert.equal(reset.pathname.split('/').at(-2), 'reset-password');
    const token = reset.pathname.split('/').at(-1);
    assert.ok(token);
    await json(await request('/api/auth/reset-password',{token,newPassword:password}));
    markPasswordSet(label);
  }
  const signIn = await request('/api/auth/sign-in/email',{email,password});
  assert.equal(signIn.status,200,`Synthetic ${label} sign-in failed (${signIn.status})`);
  const cookie=sessionCookie(signIn);
  const session=await json<AuthSession>(await request('/api/session',undefined,cookie));
  assert.equal(session.user.id,id);
  return {id,email,cookie,clinicId:typeof row.clinicId === 'string' ? row.clinicId : undefined};
}

async function resumePartialRun(): Promise<Record<'doctor1'|'doctor2'|'secretary1'|'secretary2'|'outsider', Identity>> {
  const rows = queryPilot(`WITH latest AS (
      SELECT substr(email,7,36) runId FROM auth_users WHERE email LIKE 'pilot-%@example.test' ORDER BY createdAt DESC LIMIT 1
    )
    SELECT substr(u.email,7,36) AS runId,u.id,u.email,u.emailVerified,
      (SELECT COUNT(*) FROM auth_accounts a WHERE a.userId=u.id AND a.providerId='credential') AS credentialAccounts,
      (SELECT COUNT(*) FROM clinic_memberships m WHERE m.userId=u.id AND m.status='active') AS memberships,
      (SELECT m.clinicId FROM clinic_memberships m WHERE m.userId=u.id AND m.status='active' LIMIT 1) AS clinicId,
      (SELECT m.role FROM clinic_memberships m WHERE m.userId=u.id AND m.status='active' LIMIT 1) AS membershipRole,
      substr(u.email,44,instr(substr(u.email,44),'@')-1) AS label
    FROM auth_users u JOIN latest l ON substr(u.email,7,36)=l.runId ORDER BY label`);
  assert.equal(new Set(rows.map(row => row.runId)).size, 1, 'Synthetic identities must belong to one run');
  const databaseRunId = String(rows[0]?.runId ?? '');
  assert.match(databaseRunId, /^[a-f0-9-]{36}$/);
  const labels = [...syntheticLabels].sort();
  assert.deepEqual(rows.map(row => row.label).sort(), labels, 'Expected exactly one complete set of five synthetic identities in the latest run');
  for (const row of rows) {
    assert.equal(Number(row.emailVerified),1,`Synthetic ${String(row.label)} account must be verified`);
    assert.equal(Number(row.credentialAccounts),1,`Synthetic ${String(row.label)} account must have one credential`);
    const expectsClinic = row.label !== 'outsider';
    assert.equal(Number(row.memberships),expectsClinic ? 1 : 0,`Unexpected membership state for synthetic ${String(row.label)}`);
  }
  const clinicIds = new Set(rows.filter(row => row.label !== 'outsider').map(row => row.clinicId));
  assert.equal(clinicIds.size,1,'Existing clinic members must share one clinic');
  assert.ok(clinicIds.values().next().value);
  const clinicId = String(clinicIds.values().next().value);
  const clinical = queryPilot(`SELECT
    (SELECT COUNT(*) FROM patients WHERE clinicId='${clinicId}') AS patients,
    (SELECT COUNT(*) FROM encounters WHERE clinicId='${clinicId}') AS encounters,
    (SELECT COUNT(*) FROM appointments WHERE clinicId='${clinicId}') AS appointments,
    (SELECT COUNT(*) FROM study_requests WHERE clinicId='${clinicId}') AS studies,
    (SELECT COUNT(*) FROM study_receipts WHERE clinicId='${clinicId}') AS receipts,
    (SELECT COUNT(*) FROM medical_documents WHERE clinicId='${clinicId}') AS documents`)[0];
  if (!clinical) throw new Error('Unable to verify the synthetic clinic data state.');
  assert.deepEqual(Object.values(clinical).map(Number),[0,0,0,0,0,0],'Resume only before clinical records have been created');

  prepareResumeState(databaseRunId);

  const recovered = {} as Record<'doctor1'|'doctor2'|'secretary1'|'secretary2'|'outsider',Identity>;
  for (const row of rows) {
    const label=String(row.label) as keyof typeof recovered;
    recovered[label]=await recoverIdentity(row,label);
  }
  const ownerSession = await json<AuthSession>(await request('/api/session',undefined,recovered.doctor1.cookie));
  assert.equal(ownerSession.clinic?.id,clinicId);
  assert.equal(ownerSession.canManageAccess,true);
  const members = await json<Array<{id:string;email:string;role:string;active:boolean;isAdmin:boolean}>>(await request('/api/access/members',undefined,recovered.doctor1.cookie));
  assert.equal(members.length,4);
  for (const label of ['doctor1','doctor2','secretary1','secretary2'] as const) {
    const member = members.find(item => item.id === recovered[label].id);
    if (!member?.active) throw new Error(`Synthetic ${label} membership is not active.`);
    assert.equal(member.email,recovered[label].email);
    assert.equal(member.role,label.startsWith('secretary') ? 'secretary' : 'doctor');
  }
  const outsiderSession = await json<AuthSession>(await request('/api/session',undefined,recovered.outsider.cookie));
  assert.equal(outsiderSession.onboardingRequired,true);
  const outsideClinic = await json<AuthSession>(await request('/api/onboarding/clinic',{name:'Consultorio sintético outsider'},recovered.outsider.cookie));
  const clinic = outsideClinic.clinic;
  assert.ok(clinic);
  recovered.outsider.clinicId = clinic.id;
  return recovered;
}
async function invite(owner: Identity, identity: Identity, role: 'doctor'|'secretary') {
  await json(await request('/api/access/invitations',{email:identity.email,role},owner.cookie),201);
  const token = (await capturedUrl(identity.email,'invitation')).searchParams.get('token');
  assert.ok(token);
  const session = await json<AuthSession>(await request('/api/invitations/accept',{token},identity.cookie));
  assert.equal(session.user.role,role); assert.equal(session.clinic?.id,owner.clinicId);
}
