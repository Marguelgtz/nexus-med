  assert.equal((await request(`/api/study-receipt-files/${receiptFile.id}`,undefined,outsider.cookie)).status,404);
  assert.equal((await request(`/api/study-receipts/${receipt.id}/review`,{},secretary1.cookie)).status,403);
  const reviewed=await json<StudyReceipt>(await request(`/api/study-receipts/${receipt.id}/review`,{reviewNote:'Revisión sintética'},doctor2.cookie)); assert.ok(reviewed.reviewedAt);
  const doc=await json<MedicalDocument>(await request(`/api/patients/${patient.id}/documents`,{kind:'prescription',encounterId:encounter.id,lines:[{medication:'Medicamento ficticio'}]},doctor1.cookie),201);
  assert.equal(doc.author?.id,doctor1.id); assert.equal((await request(`/api/documents/${doc.id}`,undefined,secretary1.cookie)).status,403);
