  await json(await request(`/api/appointments/${appointment.id}/reception`,{action:'arrive'},secretary2.cookie));
  await json(await request(`/api/appointments/${appointment.id}/reception`,{action:'start'},doctor1.cookie));
  const encounter=await json<EncounterDetail>(await request(`/api/patients/${patient.id}/encounters`,{occurredAt:'2026-11-16T16:00:00Z',reason:'Nota sintética remota',studies:[{category:'laboratorio',name:'Estudio sintético remoto'}]},doctor1.cookie),201);
  assert.equal(encounter.author?.id,doctor1.id);
  const saves=await Promise.all([doctor1,doctor2].map((actor,i)=>request(`/api/encounters/${encounter.id}`,{expectedVersion:encounter.version,assessment:`Edición sintética ${i}`},actor.cookie,'PATCH')));
  assert.deepEqual(saves.map(r=>r.status).sort(),[200,409]);
  const studies=await json<StudyRequest[]>(await request(`/api/encounters/${encounter.id}/studies`,undefined,doctor2.cookie));
  const study=studies[0]; assert.ok(study);
  const png=Uint8Array.from(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aNfoAAAAASUVORK5CYII=','base64'));
  const form=new FormData(); form.set('metadata',JSON.stringify({title:'Archivo sintético remoto',encounterId:encounter.id,requestId:study.id})); form.append('files',new File([png],'prueba.png',{type:'image/png'}));
  const receipt=await json<StudyReceipt>(await request(`/api/patients/${patient.id}/study-receipts`,form,secretary1.cookie),201);
  assert.equal(receipt.reviewedAt,null);
  const receiptFile=receipt.files[0]; assert.ok(receiptFile);
